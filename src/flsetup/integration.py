"""Desktop integration: launcher, menu entries, desktop shortcut, .flp association, icons."""
import os
import shlex
import shutil
import subprocess
from pathlib import Path

from . import config as C


def _run_quiet(*cmd):
    if shutil.which(cmd[0]):
        try:
            subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=60)
        except (OSError, subprocess.SubprocessError):
            pass


def _touch(d: Path):
    """Nudge desktops to rescan icons (never write a user icon cache: it can go stale)."""
    try:
        os.utime(d)
    except OSError:
        pass


LAUNCHER_TEMPLATE = r"""#!/usr/bin/env bash
# FL Studio launcher - generated by FL Studio Setup for Linux. Safe to edit.
export WINEPREFIX={prefix}
WINE={wine}
FL_EXE={fl_exe}
export WINEDEBUG="${{WINEDEBUG:--all}}"
export WINEDLLOVERRIDES="winemenubuilder.exe=d;${{WINEDLLOVERRIDES:-}}"
export PATH="$(dirname "$WINE"):$PATH"
# Slightly larger PulseAudio/PipeWire buffer avoids crackles under Wine.
export PULSE_LATENCY_MSEC="${{PULSE_LATENCY_MSEC:-60}}"
FL_WRAPPER=""
# Settings from FL Studio Setup (GameMode etc.) and your own additions.
ENV_FILE={env_file}
[ -f "$ENV_FILE" ] && . "$ENV_FILE"

case "${{1:-}}" in
  --run-exe)  shift; cd "$(dirname "$1")" && exec "$WINE" start /wait /unix "$1" ;;
  --winecfg)  exec "$WINE" winecfg ;;
  --regedit)  exec "$WINE" regedit ;;
  --taskmgr)  exec "$WINE" taskmgr ;;
  --kill)     exec "$(dirname "$WINE")/wineserver" -k ;;
  --prefix)   echo "$WINEPREFIX"; exit 0 ;;
  --help|-h)  echo "Usage: fl-studio [project.flp] | --run-exe setup.exe | --winecfg | --regedit | --taskmgr | --kill"; exit 0 ;;
esac

args=()
for a in "$@"; do
  if [ -e "$a" ]; then args+=("$("$WINE" winepath -w "$(readlink -f "$a")" 2>/dev/null)")
  else args+=("$a"); fi
done
cd "$(dirname "$FL_EXE")"
# stdin from /dev/null: FL Studio can hang on its splash screen reading the terminal.
exec $FL_WRAPPER "$WINE" "$FL_EXE" "${{args[@]}}" < /dev/null
"""

MIME_XML = """<?xml version="1.0" encoding="UTF-8"?>
<mime-info xmlns="http://www.freedesktop.org/standards/shared-mime-info">
  <mime-type type="{mime}">
    <comment>FL Studio project</comment>
    <icon name="{icon}"/>
    <glob pattern="*.flp"/>
    <glob pattern="*.FLP"/>
  </mime-type>
</mime-info>
"""


def desktop_entry(name, exec_line, icon, comment, extra=""):
    return (
        "[Desktop Entry]\nType=Application\n"
        f"Name={name}\nComment={comment}\nExec={exec_line}\nIcon={icon}\n"
        "Terminal=false\n" + extra
    )


def write_launcher(prefix: Path, wine: Path, fl_exe: Path) -> Path:
    C.BIN_DIR.mkdir(parents=True, exist_ok=True)
    C.LAUNCHER.write_text(LAUNCHER_TEMPLATE.format(
        prefix=shlex.quote(str(prefix)), wine=shlex.quote(str(wine)),
        fl_exe=shlex.quote(str(fl_exe)), env_file=shlex.quote(str(C.DATA_DIR / "launcher.env"))))
    C.LAUNCHER.chmod(0o755)
    return C.LAUNCHER


def install_icons(icon_png: Path | None, fallback_png: Path) -> list[Path]:
    src = icon_png if icon_png and icon_png.suffix == ".png" else fallback_png
    created = []
    for sub, name in (("apps", C.ICON_NAME), ("mimetypes", C.FLP_MIME.replace("/", "-"))):
        dst = C.ICON_DIR / "256x256" / sub / f"{name}.png"
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
        created.append(dst)
    _touch(C.ICON_DIR)
    return created


def _q(p):
    return '"' + str(p).replace('"', '\\"') + '"'


def install_menu_entries(menu: bool, setup_copy: Path | None) -> list[Path]:
    C.APPS_DIR.mkdir(parents=True, exist_ok=True)
    created = []
    main = C.APPS_DIR / C.DESKTOP_ID
    main.write_text(desktop_entry(
        "FL Studio", f"{_q(C.LAUNCHER)} %f", C.ICON_NAME, "Make music with FL Studio",
        "GenericName=Digital Audio Workstation\nCategories=AudioVideo;Audio;Midi;Music;\n"
        f"MimeType={C.FLP_MIME};x-scheme-handler/flstudio;\nStartupWMClass=fl64.exe\nKeywords=daw;music;beats;fruity;\n"
        + ("" if menu else "NoDisplay=true\n")))
    created.append(main)
    if setup_copy:
        s = C.APPS_DIR / C.SETUP_DESKTOP_ID
        s.write_text(desktop_entry(
            "FL Studio Setup", f"{_q(setup_copy)} --maintenance", C.ICON_NAME,
            "Update, repair or uninstall FL Studio",
            "Categories=Settings;AudioVideo;\nKeywords=uninstall;remove;update;repair;\n"))
        r = C.APPS_DIR / C.RUNEXE_DESKTOP_ID
        r.write_text(desktop_entry(
            "FL Studio Plugins", f"{_q(setup_copy)} --plugins %F", C.ICON_NAME,
            "Add or remove VST/VST3/CLAP plugins for FL Studio",
            "Categories=AudioVideo;Audio;\nKeywords=vst;vst3;clap;plugin;install;\n"
            "MimeType=application/x-ms-dos-executable;application/x-msdownload;application/x-msi;"
            "application/x-ms-installer;application/vnd.microsoft.portable-executable;application/zip;\n"))
        fb = C.APPS_DIR / "fl-studio-linux-files.desktop"
        fb.write_text(desktop_entry(
            "FL Studio Files", f"{_q(setup_copy)} --files", C.ICON_NAME,
            "Add sample packs and presets, browse FL Studio's folders",
            "Categories=AudioVideo;Audio;\nKeywords=samples;packs;presets;files;browser;\n"))
        created += [s, r, fb]
    _run_quiet("update-desktop-database", str(C.APPS_DIR))
    # Signing in to your Image-Line account in the browser comes back via flstudio:// links.
    if shutil.which("xdg-mime"):
        _run_quiet("xdg-mime", "default", C.DESKTOP_ID, "x-scheme-handler/flstudio")
    return created


def install_desktop_shortcut() -> Path | None:
    d = C.desktop_dir()
    if not d.is_dir():
        return None
    dst = d / "FL Studio.desktop"
    shutil.copyfile(C.APPS_DIR / C.DESKTOP_ID, dst)
    txt = dst.read_text().replace("NoDisplay=true\n", "")
    dst.write_text(txt)
    dst.chmod(0o755)
    _run_quiet("gio", "set", str(dst), "metadata::trusted", "true")
    return dst


def install_flp_association() -> list[Path]:
    pkg = C.MIME_DIR / "packages" / "fl-studio-linux.xml"
    pkg.parent.mkdir(parents=True, exist_ok=True)
    pkg.write_text(MIME_XML.format(mime=C.FLP_MIME, icon=C.FLP_MIME.replace("/", "-")))
    _run_quiet("update-mime-database", str(C.MIME_DIR))
    if shutil.which("xdg-mime"):
        _run_quiet("xdg-mime", "default", C.DESKTOP_ID, C.FLP_MIME)
    else:
        _set_default_manually()
    return [pkg]


def _set_default_manually():
    cfg = Path(os.environ.get("XDG_CONFIG_HOME") or C.HOME / ".config") / "mimeapps.list"
    lines = cfg.read_text().splitlines() if cfg.exists() else []
    out, in_sec, done = [], False, False
    for ln in lines:
        if ln.strip().startswith("["):
            if in_sec and not done:
                out.append(f"{C.FLP_MIME}={C.DESKTOP_ID}")
                done = True
            in_sec = ln.strip() == "[Default Applications]"
        elif in_sec and ln.startswith(C.FLP_MIME + "="):
            ln, done = f"{C.FLP_MIME}={C.DESKTOP_ID}", True
        out.append(ln)
    if not done:
        if not in_sec:
            out.append("[Default Applications]")
        out.append(f"{C.FLP_MIME}={C.DESKTOP_ID}")
    cfg.parent.mkdir(parents=True, exist_ok=True)
    cfg.write_text("\n".join(out) + "\n")


def remove_files(paths):
    for p in paths:
        p = Path(p)
        try:
            if p.is_dir() and not p.is_symlink():
                shutil.rmtree(p)
            elif p.exists() or p.is_symlink():
                p.unlink()
        except OSError:
            pass
    _run_quiet("update-desktop-database", str(C.APPS_DIR))
    _run_quiet("update-mime-database", str(C.MIME_DIR))
    _touch(C.ICON_DIR)
